-- Lab 03: Dynamic Data Masking + Row Access Policy
-- Prereq: Lab 00 + Lab 01 roles + RAW.CUSTOMERS
-- Design: policies applied on CURATED.CUSTOMERS_GOV so FR_ANALYST can SELECT
--         (Lab 01 intentionally blocked analysts from RAW.CUSTOMERS).

USE ROLE ROLE_ARCH_LAB_ADMIN;
USE WAREHOUSE WH_ARCH_XS;
USE DATABASE ARCH_INTERVIEW;

CREATE SCHEMA IF NOT EXISTS SECURE;
CREATE SCHEMA IF NOT EXISTS CURATED;

-- Working copy for governance demos
CREATE OR REPLACE TABLE CURATED.CUSTOMERS_GOV AS
SELECT CUSTOMER_ID, FULL_NAME, EMAIL, PHONE, COUNTRY, SSN_LAST4, CREATED_AT
FROM RAW.CUSTOMERS;

USE SCHEMA SECURE;

CREATE OR REPLACE MASKING POLICY MP_EMAIL_MASK AS (val STRING)
  RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('FR_COMPLIANCE', 'ROLE_ARCH_LAB_ADMIN') THEN val
    ELSE REGEXP_REPLACE(val, '.+@', '***@')
  END;

CREATE OR REPLACE TABLE RAP_COUNTRY_ENTITLEMENT (
  ROLE_NAME STRING,
  COUNTRY   STRING
);

DELETE FROM RAP_COUNTRY_ENTITLEMENT;
INSERT INTO RAP_COUNTRY_ENTITLEMENT VALUES
  ('FR_ANALYST', 'US'),
  ('FR_COMPLIANCE', 'US'),
  ('FR_COMPLIANCE', 'CA'),
  ('FR_COMPLIANCE', 'UK'),
  ('ROLE_ARCH_LAB_ADMIN', 'US'),
  ('ROLE_ARCH_LAB_ADMIN', 'CA'),
  ('ROLE_ARCH_LAB_ADMIN', 'UK'),
  ('FR_DATA_ENGINEER', 'US'),
  ('FR_DATA_ENGINEER', 'CA'),
  ('FR_DATA_ENGINEER', 'UK');

CREATE OR REPLACE ROW ACCESS POLICY RAP_CUSTOMER_COUNTRY
AS (country_code STRING) RETURNS BOOLEAN ->
  EXISTS (
    SELECT 1
    FROM SECURE.RAP_COUNTRY_ENTITLEMENT e
    WHERE e.ROLE_NAME = CURRENT_ROLE()
      AND e.COUNTRY = country_code
  );

USE SCHEMA CURATED;

ALTER TABLE CUSTOMERS_GOV MODIFY COLUMN EMAIL SET MASKING POLICY SECURE.MP_EMAIL_MASK;
ALTER TABLE CUSTOMERS_GOV ADD ROW ACCESS POLICY SECURE.RAP_CUSTOMER_COUNTRY ON (COUNTRY);

GRANT SELECT ON TABLE CURATED.CUSTOMERS_GOV TO ROLE AR_CURATED_READ;
GRANT SELECT ON TABLE CURATED.CUSTOMERS_GOV TO ROLE AR_PII_READ;

SELECT 'Lab 03 policies applied on CURATED.CUSTOMERS_GOV' AS status;
