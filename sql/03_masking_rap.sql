USE ROLE ROLE_BANK_LAB_ADMIN;
USE WAREHOUSE WH_BANK_XS;
USE DATABASE MERIDIAN_BANK;

CREATE SCHEMA IF NOT EXISTS RISK_CTRL;
CREATE SCHEMA IF NOT EXISTS CURATED;

CREATE OR REPLACE TABLE CURATED.CLIENTS_GOV AS
SELECT CLIENT_ID, FULL_NAME, EMAIL, PHONE, COUNTRY, SSN_LAST4, CREATED_AT
FROM LANDING.CLIENTS;

USE SCHEMA RISK_CTRL;

CREATE OR REPLACE MASKING POLICY MP_EMAIL_MASK AS (val STRING)
  RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('FR_COMPLIANCE', 'ROLE_BANK_LAB_ADMIN') THEN val
    ELSE REGEXP_REPLACE(val, '.+@', '***@')
  END;

CREATE OR REPLACE TABLE RAP_COUNTRY_ENTITLEMENT (
  ROLE_NAME STRING,
  COUNTRY   STRING
);

DELETE FROM RAP_COUNTRY_ENTITLEMENT;
INSERT INTO RAP_COUNTRY_ENTITLEMENT VALUES
  ('FR_ANALYST', 'US'),
  ('FR_COMPLIANCE', 'US'),
  ('FR_COMPLIANCE', 'CA'),
  ('FR_COMPLIANCE', 'UK'),
  ('ROLE_BANK_LAB_ADMIN', 'US'),
  ('ROLE_BANK_LAB_ADMIN', 'CA'),
  ('ROLE_BANK_LAB_ADMIN', 'UK'),
  ('FR_DATA_ENGINEER', 'US'),
  ('FR_DATA_ENGINEER', 'CA'),
  ('FR_DATA_ENGINEER', 'UK');

CREATE OR REPLACE ROW ACCESS POLICY RAP_CLIENT_COUNTRY
AS (country_code STRING) RETURNS BOOLEAN ->
  EXISTS (
    SELECT 1 FROM RISK_CTRL.RAP_COUNTRY_ENTITLEMENT e
    WHERE e.ROLE_NAME = CURRENT_ROLE() AND e.COUNTRY = country_code
  );

USE SCHEMA CURATED;
ALTER TABLE CLIENTS_GOV MODIFY COLUMN EMAIL SET MASKING POLICY RISK_CTRL.MP_EMAIL_MASK;
ALTER TABLE CLIENTS_GOV ADD ROW ACCESS POLICY RISK_CTRL.RAP_CLIENT_COUNTRY ON (COUNTRY);

GRANT SELECT ON TABLE CURATED.CLIENTS_GOV TO ROLE AR_CURATED_READ;
GRANT SELECT ON TABLE CURATED.CLIENTS_GOV TO ROLE AR_PII_READ;

SELECT 'Lab 03 policies on CURATED.CLIENTS_GOV' AS status;
