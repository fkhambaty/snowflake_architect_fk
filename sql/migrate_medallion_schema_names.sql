-- ============================================================
-- Migrate existing Meridian Bank → medallion names
-- Run AFTER (or including) schema renames.
-- ROLE_BANK_LAB_ADMIN. Idempotent where possible.
-- ============================================================

USE ROLE ROLE_BANK_LAB_ADMIN;
USE WAREHOUSE WH_BANK_XS;
USE DATABASE MERIDIAN_BANK;

-- 1) Schemas (skip if you already renamed)
ALTER SCHEMA IF EXISTS LANDING RENAME TO BRONZE_LANDING;
ALTER SCHEMA IF EXISTS CURATED RENAME TO SILVER_CURATED;
ALTER SCHEMA IF EXISTS FINANCE_MART RENAME TO GOLD_MART;

CREATE SCHEMA IF NOT EXISTS BRONZE_LANDING;
CREATE SCHEMA IF NOT EXISTS SILVER_CURATED;
CREATE SCHEMA IF NOT EXISTS RISK_CTRL;
CREATE SCHEMA IF NOT EXISTS GOLD_MART;
CREATE SCHEMA IF NOT EXISTS FILE_IN;
CREATE SCHEMA IF NOT EXISTS UTILS;

-- 2) New access key-rings
CREATE ROLE IF NOT EXISTS AR_BRONZE_LANDING_READ;
CREATE ROLE IF NOT EXISTS AR_SILVER_CURATED_READ;

GRANT USAGE ON DATABASE MERIDIAN_BANK TO ROLE AR_BRONZE_LANDING_READ;
GRANT USAGE ON DATABASE MERIDIAN_BANK TO ROLE AR_SILVER_CURATED_READ;

GRANT USAGE ON SCHEMA BRONZE_LANDING TO ROLE AR_BRONZE_LANDING_READ;
GRANT USAGE ON SCHEMA SILVER_CURATED TO ROLE AR_SILVER_CURATED_READ;

GRANT SELECT ON ALL TABLES IN SCHEMA BRONZE_LANDING TO ROLE AR_BRONZE_LANDING_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA BRONZE_LANDING TO ROLE AR_BRONZE_LANDING_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA SILVER_CURATED TO ROLE AR_SILVER_CURATED_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SILVER_CURATED TO ROLE AR_SILVER_CURATED_READ;
GRANT SELECT ON ALL VIEWS IN SCHEMA SILVER_CURATED TO ROLE AR_SILVER_CURATED_READ;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SILVER_CURATED TO ROLE AR_SILVER_CURATED_READ;

-- Clip new key-rings onto job badges
GRANT ROLE AR_BRONZE_LANDING_READ TO ROLE FR_DATA_ENGINEER;
GRANT ROLE AR_SILVER_CURATED_READ TO ROLE FR_ANALYST;
GRANT ROLE AR_SILVER_CURATED_READ TO ROLE FR_DATA_ENGINEER;
GRANT ROLE AR_SILVER_CURATED_READ TO ROLE FR_COMPLIANCE;

-- Explicit object grants (skip any line that errors if you have not built that lab yet)
GRANT SELECT ON VIEW SILVER_CURATED.V_CLIENT_DIRECTORY TO ROLE AR_SILVER_CURATED_READ;  -- Lab 01
GRANT SELECT ON TABLE SILVER_CURATED.CLIENTS_GOV TO ROLE AR_SILVER_CURATED_READ;       -- Lab 03
GRANT SELECT ON TABLE SILVER_CURATED.CLIENTS_GOV TO ROLE AR_PII_READ;                  -- Lab 03

-- 3) Drop old key-ring names (safe after grants above)
DROP ROLE IF EXISTS AR_LANDING_READ;
DROP ROLE IF EXISTS AR_CURATED_READ;

SELECT 'Medallion migration complete' AS status;
SHOW SCHEMAS IN DATABASE MERIDIAN_BANK;
