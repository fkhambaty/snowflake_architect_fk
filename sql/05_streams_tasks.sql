-- Lab 05: Stream + Task (append-only CDC demo) — keep simple & reliable
USE ROLE ROLE_ARCH_LAB_ADMIN;
USE WAREHOUSE WH_ARCH_XS;
USE DATABASE ARCH_INTERVIEW;
USE SCHEMA CURATED;

CREATE OR REPLACE TABLE ORDERS_SILVER_CDC (
  ORDER_ID NUMBER,
  CUSTOMER_ID NUMBER,
  STATUS STRING,
  ORDER_TOTAL NUMBER(12,2),
  UPDATED_AT TIMESTAMP_NTZ,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Append-only stream: fires on new inserts to RAW.ORDERS_EVENTS
CREATE OR REPLACE STREAM RAW.ORDERS_EVENTS_STR
  ON TABLE RAW.ORDERS_EVENTS
  APPEND_ONLY = TRUE;

CREATE OR REPLACE TASK CURATED.TASK_ORDERS_CDC
  WAREHOUSE = WH_ARCH_XS
  SCHEDULE = 'USING CRON 0 0 1 1 * UTC'  -- rare schedule; we EXECUTE manually
  WHEN SYSTEM$STREAM_HAS_DATA('RAW.ORDERS_EVENTS_STR')
AS
  INSERT INTO CURATED.ORDERS_SILVER_CDC (ORDER_ID, CUSTOMER_ID, STATUS, ORDER_TOTAL, UPDATED_AT)
  SELECT ORDER_ID, CUSTOMER_ID, STATUS, ORDER_TOTAL, UPDATED_AT
  FROM RAW.ORDERS_EVENTS_STR;

-- Needs EXECUTE TASK privilege (Lab 00 bootstrap)
ALTER TASK CURATED.TASK_ORDERS_CDC RESUME;

-- Idempotent demo row (safe if you re-run the lab)
DELETE FROM CURATED.ORDERS_SILVER_CDC WHERE ORDER_ID = 1099;
DELETE FROM RAW.ORDERS_EVENTS WHERE ORDER_ID = 1099;

INSERT INTO RAW.ORDERS_EVENTS VALUES
  (1099, 1, 'CREATED', 1.00, CURRENT_TIMESTAMP());

EXECUTE TASK CURATED.TASK_ORDERS_CDC;

SELECT * FROM CURATED.ORDERS_SILVER_CDC WHERE ORDER_ID = 1099;

ALTER TASK CURATED.TASK_ORDERS_CDC SUSPEND;

SELECT 'Lab 05 stream/task OK — task suspended to save credits' AS status;
