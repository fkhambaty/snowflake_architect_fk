USE ROLE ROLE_BANK_LAB_ADMIN;
USE WAREHOUSE WH_BANK_XS;
USE DATABASE MERIDIAN_BANK;
CREATE SCHEMA IF NOT EXISTS FILE_IN;
USE SCHEMA FILE_IN;

CREATE OR REPLACE FILE FORMAT FF_CSV_SIMPLE TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 0;
CREATE OR REPLACE STAGE STG_TXN_INTERNAL FILE_FORMAT = FF_CSV_SIMPLE;

CREATE OR REPLACE TABLE BRONZE_LANDING.TXN_LANDING (
  TXN_ID NUMBER, CLIENT_ID NUMBER, STATUS STRING, AMOUNT NUMBER(12,2)
);

COPY INTO @STG_TXN_INTERNAL/txn_day1.csv.gz FROM (
  SELECT * FROM VALUES (2001, 1, 'POSTED', 10.00), (2002, 2, 'POSTED', 20.00), (2003, 3, 'SETTLED', 30.00)
) OVERWRITE = TRUE SINGLE = TRUE;

COPY INTO BRONZE_LANDING.TXN_LANDING FROM @STG_TXN_INTERNAL
FILE_FORMAT = (FORMAT_NAME = 'FILE_IN.FF_CSV_SIMPLE')
PATTERN = '.*txn_day1.csv.gz' ON_ERROR = 'ABORT_STATEMENT';

SELECT * FROM BRONZE_LANDING.TXN_LANDING ORDER BY TXN_ID;
SELECT 'Lab 06 BRONZE_LANDING COPY OK' AS status;
