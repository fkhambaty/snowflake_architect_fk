-- Lab 06: Internal stage unload → COPY INTO table (landing zone pattern)
-- No AWS/Azure needed. Interview story: Snowpipe automates this COPY on external stages.
USE ROLE ROLE_ARCH_LAB_ADMIN;
USE WAREHOUSE WH_ARCH_XS;
USE DATABASE ARCH_INTERVIEW;

CREATE SCHEMA IF NOT EXISTS STAGE_DATA;
USE SCHEMA STAGE_DATA;

CREATE OR REPLACE FILE FORMAT FF_CSV_SIMPLE
  TYPE = CSV
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  SKIP_HEADER = 0;

CREATE OR REPLACE STAGE STG_ORDERS_INTERNAL
  FILE_FORMAT = FF_CSV_SIMPLE;

CREATE OR REPLACE TABLE RAW.ORDERS_LANDING (
  ORDER_ID NUMBER,
  CUSTOMER_ID NUMBER,
  STATUS STRING,
  ORDER_TOTAL NUMBER(12,2)
);

-- 1) "File lands" — unload query results into the stage as a CSV
COPY INTO @STG_ORDERS_INTERNAL/orders_day1.csv.gz
FROM (
  SELECT * FROM VALUES
    (2001, 1, 'CREATED', 10.00),
    (2002, 2, 'CREATED', 20.00),
    (2003, 3, 'SHIPPED', 30.00)
)
OVERWRITE = TRUE
SINGLE = TRUE;

LIST @STG_ORDERS_INTERNAL;

-- 2) Load stage file into landing table (this is what Snowpipe automates)
COPY INTO RAW.ORDERS_LANDING
FROM @STG_ORDERS_INTERNAL
FILE_FORMAT = (FORMAT_NAME = 'STAGE_DATA.FF_CSV_SIMPLE')
PATTERN = '.*orders_day1.csv.gz'
ON_ERROR = 'ABORT_STATEMENT';

SELECT * FROM RAW.ORDERS_LANDING ORDER BY ORDER_ID;

SELECT 'Lab 06 landing COPY OK' AS status;
