-- Lab 08: Clustering concepts on a bigger demo table (still small enough for trial)
USE ROLE ROLE_ARCH_LAB_ADMIN;
USE WAREHOUSE WH_ARCH_XS;
USE DATABASE ARCH_INTERVIEW;
USE SCHEMA CURATED;

CREATE OR REPLACE TABLE BIG_EVENTS AS
SELECT
  SEQ4() AS EVENT_ID,
  UNIFORM(1, 5, RANDOM()) AS CUSTOMER_ID,
  DATEADD('day', -UNIFORM(0, 364, RANDOM()), CURRENT_DATE()) AS EVENT_DATE,
  UNIFORM(1, 100, RANDOM()) / 1 AS AMOUNT
FROM TABLE(GENERATOR(ROWCOUNT => 200000));

-- Baseline clustering info on EVENT_DATE (before defining a key)
SELECT SYSTEM$CLUSTERING_INFORMATION('CURATED.BIG_EVENTS', '(EVENT_DATE)');

-- Add clustering key (automatic clustering may run asynchronously)
ALTER TABLE BIG_EVENTS CLUSTER BY (EVENT_DATE);

SELECT SYSTEM$CLUSTERING_INFORMATION('CURATED.BIG_EVENTS', '(EVENT_DATE)');

-- Query that benefits from pruning on EVENT_DATE
SELECT COUNT(*), SUM(AMOUNT)
FROM BIG_EVENTS
WHERE EVENT_DATE >= DATEADD('day', -7, CURRENT_DATE());

SELECT 'Lab 08 clustering demo ready — compare Query Profile prune stats' AS status;
