USE WAREHOUSE WH_BANK_XS;
USE DATABASE MERIDIAN_BANK;
USE SCHEMA SILVER_CURATED;

CREATE OR REPLACE TABLE BIG_EVENTS AS
SELECT SEQ4() AS EVENT_ID, UNIFORM(1, 5, RANDOM()) AS CLIENT_ID,
  DATEADD('day', -UNIFORM(0, 364, RANDOM()), CURRENT_DATE()) AS EVENT_DATE,
  UNIFORM(1, 100, RANDOM()) / 1 AS AMOUNT
FROM TABLE(GENERATOR(ROWCOUNT => 200000));

SELECT SYSTEM$CLUSTERING_INFORMATION('SILVER_CURATED.BIG_EVENTS', '(EVENT_DATE)');
ALTER TABLE BIG_EVENTS CLUSTER BY (EVENT_DATE);
SELECT COUNT(*), SUM(AMOUNT) FROM BIG_EVENTS
WHERE EVENT_DATE >= DATEADD('day', -7, CURRENT_DATE());
