-- Lab 01: functional vs access roles (architect pattern)
-- Prerequisites:
--   1) Lab 00 bootstrap (updated) OR sql/00_privilege_repair.sql
--   2) sql/00_sample_data.sql (RAW.CUSTOMERS)
--
-- Design note:
--   Role CREATE/GRANT of roles can run as ROLE_ARCH_LAB_ADMIN only if that role
--   has CREATE ROLE ON ACCOUNT (granted in Lab 00). Object grants use lab admin
--   as database owner.

USE ROLE ROLE_ARCH_LAB_ADMIN;
USE WAREHOUSE WH_ARCH_XS;
USE DATABASE ARCH_INTERVIEW;

/* ============================================================
   ACCESS ROLES (permissions only — granted to functional roles)
   ============================================================ */
CREATE ROLE IF NOT EXISTS AR_RAW_READ;
CREATE ROLE IF NOT EXISTS AR_CURATED_READ;
CREATE ROLE IF NOT EXISTS AR_PII_READ;

/* ============================================================
   FUNCTIONAL ROLES (what people / services "are")
   ============================================================ */
CREATE ROLE IF NOT EXISTS FR_ANALYST;
CREATE ROLE IF NOT EXISTS FR_DATA_ENGINEER;
CREATE ROLE IF NOT EXISTS FR_COMPLIANCE;

-- Warehouse for everyone in the lab (needs WITH GRANT OPTION from Lab 00)
GRANT USAGE ON WAREHOUSE WH_ARCH_XS TO ROLE FR_ANALYST;
GRANT USAGE ON WAREHOUSE WH_ARCH_XS TO ROLE FR_DATA_ENGINEER;
GRANT USAGE ON WAREHOUSE WH_ARCH_XS TO ROLE FR_COMPLIANCE;

-- Database / schema usage on access roles
GRANT USAGE ON DATABASE ARCH_INTERVIEW TO ROLE AR_RAW_READ;
GRANT USAGE ON DATABASE ARCH_INTERVIEW TO ROLE AR_CURATED_READ;
GRANT USAGE ON DATABASE ARCH_INTERVIEW TO ROLE AR_PII_READ;

GRANT USAGE ON SCHEMA RAW TO ROLE AR_RAW_READ;
GRANT USAGE ON SCHEMA CURATED TO ROLE AR_CURATED_READ;
GRANT USAGE ON SCHEMA SECURE TO ROLE AR_PII_READ;
GRANT USAGE ON SCHEMA RAW TO ROLE AR_PII_READ;

-- Table grants on access roles
GRANT SELECT ON ALL TABLES IN SCHEMA RAW TO ROLE AR_RAW_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW TO ROLE AR_RAW_READ;

GRANT SELECT ON ALL TABLES IN SCHEMA CURATED TO ROLE AR_CURATED_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CURATED TO ROLE AR_CURATED_READ;

GRANT SELECT ON ALL TABLES IN SCHEMA RAW TO ROLE AR_PII_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW TO ROLE AR_PII_READ;

-- Functional <- Access (the important graph)
GRANT ROLE AR_CURATED_READ TO ROLE FR_ANALYST;

GRANT ROLE AR_RAW_READ TO ROLE FR_DATA_ENGINEER;
GRANT ROLE AR_CURATED_READ TO ROLE FR_DATA_ENGINEER;

GRANT ROLE AR_PII_READ TO ROLE FR_COMPLIANCE;
GRANT ROLE AR_CURATED_READ TO ROLE FR_COMPLIANCE;

-- Attach functional roles to YOUR user for testing
SET uname = (SELECT CURRENT_USER());
GRANT ROLE FR_ANALYST TO USER IDENTIFIER($uname);
GRANT ROLE FR_DATA_ENGINEER TO USER IDENTIFIER($uname);
GRANT ROLE FR_COMPLIANCE TO USER IDENTIFIER($uname);

-- Curated non-PII view for analysts
USE SCHEMA CURATED;
CREATE OR REPLACE VIEW V_CUSTOMERS_PUBLIC AS
SELECT
  CUSTOMER_ID,
  FULL_NAME,
  COUNTRY,
  CREATED_AT
FROM RAW.CUSTOMERS;

GRANT SELECT ON VIEW V_CUSTOMERS_PUBLIC TO ROLE AR_CURATED_READ;

SELECT 'RBAC objects created' AS status;
