-- Lab 01: Meridian Bank RBAC — FR_ job badges + AR_ key-rings
USE ROLE ROLE_BANK_LAB_ADMIN;
USE WAREHOUSE WH_BANK_XS;
USE DATABASE MERIDIAN_BANK;

CREATE ROLE IF NOT EXISTS AR_LANDING_READ;
CREATE ROLE IF NOT EXISTS AR_CURATED_READ;
CREATE ROLE IF NOT EXISTS AR_PII_READ;

CREATE ROLE IF NOT EXISTS FR_ANALYST;
CREATE ROLE IF NOT EXISTS FR_DATA_ENGINEER;
CREATE ROLE IF NOT EXISTS FR_COMPLIANCE;

GRANT USAGE ON WAREHOUSE WH_BANK_XS TO ROLE FR_ANALYST;
GRANT USAGE ON WAREHOUSE WH_BANK_XS TO ROLE FR_DATA_ENGINEER;
GRANT USAGE ON WAREHOUSE WH_BANK_XS TO ROLE FR_COMPLIANCE;

GRANT USAGE ON DATABASE MERIDIAN_BANK TO ROLE AR_LANDING_READ;
GRANT USAGE ON DATABASE MERIDIAN_BANK TO ROLE AR_CURATED_READ;
GRANT USAGE ON DATABASE MERIDIAN_BANK TO ROLE AR_PII_READ;

GRANT USAGE ON SCHEMA LANDING TO ROLE AR_LANDING_READ;
GRANT USAGE ON SCHEMA CURATED TO ROLE AR_CURATED_READ;
GRANT USAGE ON SCHEMA RISK_CTRL TO ROLE AR_PII_READ;
GRANT USAGE ON SCHEMA LANDING TO ROLE AR_PII_READ;

GRANT SELECT ON ALL TABLES IN SCHEMA LANDING TO ROLE AR_LANDING_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LANDING TO ROLE AR_LANDING_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA CURATED TO ROLE AR_CURATED_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CURATED TO ROLE AR_CURATED_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA LANDING TO ROLE AR_PII_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LANDING TO ROLE AR_PII_READ;

GRANT ROLE AR_CURATED_READ TO ROLE FR_ANALYST;
GRANT ROLE AR_LANDING_READ TO ROLE FR_DATA_ENGINEER;
GRANT ROLE AR_CURATED_READ TO ROLE FR_DATA_ENGINEER;
GRANT ROLE AR_PII_READ TO ROLE FR_COMPLIANCE;
GRANT ROLE AR_CURATED_READ TO ROLE FR_COMPLIANCE;

SET uname = (SELECT CURRENT_USER());
GRANT ROLE FR_ANALYST TO USER IDENTIFIER($uname);
GRANT ROLE FR_DATA_ENGINEER TO USER IDENTIFIER($uname);
GRANT ROLE FR_COMPLIANCE TO USER IDENTIFIER($uname);

USE SCHEMA CURATED;
CREATE OR REPLACE VIEW V_CLIENT_DIRECTORY AS
SELECT CLIENT_ID, FULL_NAME, COUNTRY, CREATED_AT
FROM LANDING.CLIENTS;

GRANT SELECT ON VIEW V_CLIENT_DIRECTORY TO ROLE AR_CURATED_READ;

SELECT 'Lab 01 Meridian Bank RBAC ready' AS status;
