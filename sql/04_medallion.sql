USE ROLE ROLE_BANK_LAB_ADMIN;
USE WAREHOUSE WH_BANK_XS;
USE DATABASE MERIDIAN_BANK;
CREATE SCHEMA IF NOT EXISTS GOLD_MART;

CREATE OR REPLACE TABLE SILVER_CURATED.SILVER_TXNS AS
SELECT TXN_ID, CLIENT_ID, UPPER(STATUS) AS STATUS, AMOUNT, UPDATED_AT
FROM bronze_landing.txn_events
WHERE AMOUNT >= 0;

CREATE OR REPLACE TABLE GOLD_MART.GOLD_CLIENT_SUMMARY AS
SELECT CLIENT_ID, COUNT(*) AS TXN_COUNT, SUM(AMOUNT) AS LIFETIME_VALUE, MAX(UPDATED_AT) AS LAST_UPDATE
FROM SILVER_CURATED.SILVER_TXNS
GROUP BY CLIENT_ID;

SELECT 'BRONZE_LANDING' AS layer, COUNT(*) AS n FROM bronze_landing.txn_events
UNION ALL SELECT 'silver', COUNT(*) FROM SILVER_CURATED.SILVER_TXNS
UNION ALL SELECT 'gold', COUNT(*) FROM GOLD_MART.GOLD_CLIENT_SUMMARY;
