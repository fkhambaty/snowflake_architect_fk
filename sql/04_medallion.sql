-- Lab 04: Medallion layers (Bronze/Silver/Gold) — simple working model
USE ROLE ROLE_ARCH_LAB_ADMIN;
USE WAREHOUSE WH_ARCH_XS;
USE DATABASE ARCH_INTERVIEW;

CREATE SCHEMA IF NOT EXISTS MART;

-- Bronze = RAW (already have CUSTOMERS / ORDERS_EVENTS)
-- Silver = cleaned
CREATE OR REPLACE TABLE CURATED.SILVER_ORDERS AS
SELECT
  ORDER_ID,
  CUSTOMER_ID,
  UPPER(STATUS) AS STATUS,
  ORDER_TOTAL,
  UPDATED_AT
FROM RAW.ORDERS_EVENTS
WHERE ORDER_TOTAL >= 0;

-- Gold = business mart
CREATE OR REPLACE TABLE MART.GOLD_ORDER_SUMMARY AS
SELECT
  CUSTOMER_ID,
  COUNT(*) AS ORDER_COUNT,
  SUM(ORDER_TOTAL) AS LIFETIME_VALUE,
  MAX(UPDATED_AT) AS LAST_UPDATE
FROM CURATED.SILVER_ORDERS
GROUP BY CUSTOMER_ID;

SELECT 'bronze rows' AS layer, COUNT(*) AS n FROM RAW.ORDERS_EVENTS
UNION ALL
SELECT 'silver rows', COUNT(*) FROM CURATED.SILVER_ORDERS
UNION ALL
SELECT 'gold customers', COUNT(*) FROM MART.GOLD_ORDER_SUMMARY;

SELECT * FROM MART.GOLD_ORDER_SUMMARY ORDER BY LIFETIME_VALUE DESC;
