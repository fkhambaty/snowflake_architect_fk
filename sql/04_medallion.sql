USE ROLE ROLE_BANK_LAB_ADMIN;
USE WAREHOUSE WH_BANK_XS;
USE DATABASE MERIDIAN_BANK;
CREATE SCHEMA IF NOT EXISTS FINANCE_MART;

CREATE OR REPLACE TABLE CURATED.SILVER_TXNS AS
SELECT TXN_ID, CLIENT_ID, UPPER(STATUS) AS STATUS, AMOUNT, UPDATED_AT
FROM LANDING.TXN_EVENTS
WHERE AMOUNT >= 0;

CREATE OR REPLACE TABLE FINANCE_MART.GOLD_CLIENT_SUMMARY AS
SELECT CLIENT_ID, COUNT(*) AS TXN_COUNT, SUM(AMOUNT) AS LIFETIME_VALUE, MAX(UPDATED_AT) AS LAST_UPDATE
FROM CURATED.SILVER_TXNS
GROUP BY CLIENT_ID;

SELECT 'landing' AS layer, COUNT(*) AS n FROM LANDING.TXN_EVENTS
UNION ALL SELECT 'silver', COUNT(*) FROM CURATED.SILVER_TXNS
UNION ALL SELECT 'gold', COUNT(*) FROM FINANCE_MART.GOLD_CLIENT_SUMMARY;
