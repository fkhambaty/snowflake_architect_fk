-- Lab 13: FinOps / cost visibility (ACCOUNT_USAGE has latency up to ~45 min–3 hrs)
USE ROLE ACCOUNTADMIN;  -- ACCOUNT_USAGE typically needs imported privileges / ACCOUNTADMIN

-- Warehouse credit burn (last 7 days)
SELECT
  WAREHOUSE_NAME,
  SUM(CREDITS_USED) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())
GROUP BY 1
ORDER BY 2 DESC NULLS LAST;

-- Expensive queries (last 24h) — adjust if empty due to latency
SELECT
  QUERY_ID,
  USER_NAME,
  ROLE_NAME,
  WAREHOUSE_NAME,
  TOTAL_ELAPSED_TIME/1000 AS SECONDS,
  BYTES_SCANNED,
  QUERY_TEXT
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD('day', -1, CURRENT_TIMESTAMP())
ORDER BY TOTAL_ELAPSED_TIME DESC NULLS LAST
LIMIT 20;

