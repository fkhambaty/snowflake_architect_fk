-- Replace MERIDIAN_LOCATOR_HERE with CURRENT_ACCOUNT() from the provider worksheet.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS WH_NORA_XS
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS NORA_FROM_MERIDIAN
  FROM SHARE MERIDIAN_LOCATOR_HERE.SHARE_MERIDIAN_TXNS;

GRANT IMPORTED PRIVILEGES ON DATABASE NORA_FROM_MERIDIAN TO ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_NORA_XS;
USE DATABASE NORA_FROM_MERIDIAN;

SHOW VIEWS;
SELECT * FROM SILVER_CURATED.V_SHARE_TXNS LIMIT 20;

SELECT 'Lab 10 consumer: Nora can read the share window' AS status;
