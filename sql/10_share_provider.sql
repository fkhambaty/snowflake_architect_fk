-- Lab 10: Secure Data Share (provider side) — works in one account; consumer needs 2nd account
USE ROLE ROLE_ARCH_LAB_ADMIN;
USE WAREHOUSE WH_ARCH_XS;
USE DATABASE ARCH_INTERVIEW;

CREATE OR REPLACE SECURE VIEW CURATED.V_SHARE_ORDERS AS
SELECT ORDER_ID, CUSTOMER_ID, STATUS, ORDER_TOTAL
FROM RAW.ORDERS_EVENTS;

-- CREATE SHARE requires CREATE SHARE privilege (Lab 00 repair). Re-run safe via DROP.
DROP SHARE IF EXISTS SHARE_ARCH_ORDERS;
CREATE SHARE SHARE_ARCH_ORDERS;
GRANT USAGE ON DATABASE ARCH_INTERVIEW TO SHARE SHARE_ARCH_ORDERS;
GRANT USAGE ON SCHEMA CURATED TO SHARE SHARE_ARCH_ORDERS;
GRANT SELECT ON VIEW CURATED.V_SHARE_ORDERS TO SHARE SHARE_ARCH_ORDERS;

SHOW SHARES LIKE 'SHARE_ARCH_ORDERS';
SHOW GRANTS TO SHARE SHARE_ARCH_ORDERS;

-- To finish cross-account: ACCOUNTADMIN runs
-- ALTER SHARE SHARE_ARCH_ORDERS ADD ACCOUNTS = <consumer_account_locator>;
SELECT 'Lab 10 share created with secure view — add consumer account to complete' AS status;
